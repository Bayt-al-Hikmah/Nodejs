// Comparison and Logical Operators

// Comparison Operators

console.log(5 > 4 );    // Greater then          | result true
console.log(4 < 2);     // Lesser then           | result false
console.log(4 == 4);    // Equal to              | result true
console.log(1 != 1);    // Not equal to          | result false
console.log(2 >= 2);    // Greater then or equal | result true
console.log(4 <= 5);    // Less then or equal    | result true
console.log("4" === 4); // Identical             | result false
console.log("4" !== 4); // Not Identical         | result true

// Logical Operators

console.log(true || false);    // Logical or    | result true
console.log(true && false);    // Logical and   | result false
console.log(!false);           // Logical not   | result true